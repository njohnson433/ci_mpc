#!/bin/bash
# End-to-end test: headless Isaac Sim + in-process ros2_control + cartesian_impedance_controller.
# Checks that the arm holds its pose after activation and reaches a reference pose.
# Usage: run_impedance_test.sh [extra args for check_impedance_tracking.py]
# Uses its own ROS_DOMAIN_ID (default 42) so it doesn't talk to other ROS nodes.
# CONTROLLER_CONFIG=/path/to.yaml overrides the controller YAML (e.g. for gain sweeps).
# CHECKER=/path/to/script.py replaces the ROS-side script (it gets --sync-dir plus the extra args),
#   e.g. CHECKER=ci_mpc_sysid/scripts/run_joint_id.py with CONTROLLER_CONFIG=.../isaac_sysid.yaml.
# GUI=1 opens the Isaac Sim window (uses the current DISPLAY / XAUTHORITY).
# SCENE=/path/to/scene.usd overrides the scene (must sit next to the fr3/ asset folder).
# PICK_PLACE=1 adds the table, cube and simulated gripper (scripts/isaac/pick_place_scene.py);
#   OBJECT_SIZE=x,y,z [m] and OBJECT_YAW=deg change the object; BOXES='x,y,yaw;...' adds more boxes.
# WRIST_FT=1 logs the simulated wrist F/T sensor to <sync>/wrist_ft.csv (scripts/isaac/wrist_ft.py).
# CAMERA=1 adds the simulated Gemini 305 wrist camera (scripts/isaac/wrist_camera.py).
# PEG=1 adds the Factory 8 mm peg-in-hole (scripts/isaac/peg_scene.py); PEG_HOLE_XY=x,y, PEG_DROP_TEST=1,
#   PEG_FRICTION=mu, PEG_HOLE_TILT=deg (held-out variations).
# GEAR=1 adds the Factory gear mesh (held-out H2, scripts/isaac/gear_scene.py); GEAR_BASE_XY=x,y, GEAR_DROP_TEST=1.
# PUSH=1 adds the table, slider box and pusher rod (scripts/isaac/push_scene.py); PUSH_XY=x,y, PUSH_YAW=deg.
# Do not edit this file while a run is using it: bash reads scripts incrementally.
HERE=$(cd "$(dirname "$0")" && pwd)
CHECKER=${CHECKER:-$HERE/../check_impedance_tracking.py}
export ROS_DOMAIN_ID=${ROS_DOMAIN_ID:-42}
SYNC=$(mktemp -d)
LOG=${LOG:-$SYNC/isaac.log}
echo "sync dir $SYNC, Isaac log $LOG"

# Isaac side in a clean environment (no /opt/ros sourced)
env -i HOME="$HOME" USER="$USER" PATH="$HOME/.local/bin:/usr/local/bin:/usr/bin:/bin" \
    ROS_DOMAIN_ID="$ROS_DOMAIN_ID" OMNI_KIT_ACCEPT_EULA=YES \
    ${GUI:+DISPLAY="$DISPLAY" XAUTHORITY="$XAUTHORITY"} \
    "$HERE/../isaac_ros.sh" --python "$HERE/headless_impedance_sim.py" --sync-dir "$SYNC" ${CONTROLLER_CONFIG:+--config "$CONTROLLER_CONFIG"} ${GUI:+--gui} ${SCENE:+--scene "$SCENE"} ${PICK_PLACE:+--pick-place} ${OBJECT_SIZE:+--object-size "$OBJECT_SIZE"} ${OBJECT_YAW:+--object-yaw "$OBJECT_YAW"} ${BOXES:+--boxes "$BOXES"} ${WRIST_FT:+--wrist-ft} ${CAMERA:+--camera} ${PEG:+--peg} ${GEAR:+--gear} ${GEAR_BASE_XY:+--gear-base-xy "$GEAR_BASE_XY"} ${GEAR_DROP_TEST:+--gear-drop-test} ${PEG_HOLE_XY:+--peg-hole-xy "$PEG_HOLE_XY"} ${PEG_DROP_TEST:+--peg-drop-test} ${PEG_FRICTION:+--peg-friction "$PEG_FRICTION"} ${PEG_HOLE_TILT:+--peg-hole-tilt "$PEG_HOLE_TILT"} ${PUSH:+--push} ${PUSH_XY:+--push-xy "$PUSH_XY"} ${PUSH_YAW:+--push-yaw "$PUSH_YAW"} > "$LOG" 2>&1 &
ISAAC_PID=$!

# ROS side
(
  source /opt/ros/humble/setup.bash
  source ~/franka_ros2_ws/install/setup.bash
  exec python3 "$CHECKER" --sync-dir "$SYNC" "$@"
) &
CHECK_PID=$!
# If Isaac exits early (crash, missing prim), stop the checker instead of letting it wait forever
( while kill -0 $ISAAC_PID 2>/dev/null; do sleep 1; done
  kill -0 $CHECK_PID 2>/dev/null && echo "Isaac exited before the checker finished" && kill $CHECK_PID ) &
WATCH_PID=$!
wait $CHECK_PID
RC=$?
kill $WATCH_PID 2>/dev/null
touch "$SYNC/done"
wait $ISAAC_PID
grep -E "^\[sim\]|cartesian_impedance|ros2.control\]|Error|error" "$LOG" | grep -v -i "warn" | tail -20
exit $RC
